#!/usr/bin/env python3
"""Offline Snowcap atlas -> LVGL 9 I8/BGRA palettes. Requires Pillow 12.3.0.

Run from any directory: python3 firmware/tools/avatar_convert.py [--check]
All 57 original used cells are kept; no resizing, mirroring or WebP at runtime.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "main/assets"
SOURCE = ASSETS / "avatar_source/spritesheet.webp"
ROWS = [("idle", 6), ("running-right", 8), ("running-left", 8),
        ("waving", 4), ("jumping", 5), ("failed", 8),
        ("waiting", 6), ("running", 6), ("review", 6)]
W, H, FRAME_BYTES = 192, 208, 40960


def convert():
    sheet = Image.open(SOURCE).convert("RGBA")
    assert sheet.size == (8 * W, 9 * H), sheet.size
    validation = json.loads((ASSETS / "avatar_source/validation.json").read_text())
    review = json.loads((ASSETS / "avatar_source/review.json").read_text())
    assert validation["ok"] and review["ok"]
    assert [(r["state"], r["actual_frames"]) for r in review["rows"]] == ROWS
    chunks, frames, previews = [], [], []
    for row, (name, count) in enumerate(ROWS):
        for col in range(8):
            cell = sheet.crop((col * W, row * H, (col + 1) * W, (row + 1) * H))
            if col >= count:
                assert cell.getchannel("A").getbbox() is None
                continue
            # Canonicalize invisible RGB, otherwise invisible WebP chroma wastes colors.
            pixels = [(r, g, b, a) if a else (0, 0, 0, 0) for r, g, b, a in cell.get_flattened_data()]
            cell.putdata(pixels)
            indexed = cell.quantize(colors=255, method=Image.Quantize.FASTOCTREE,
                                    dither=Image.Dither.NONE)
            palette = indexed.getpalette("RGBA")
            palette += [0] * (1024 - len(palette))
            palette[1020:1024] = [0, 0, 0, 0]  # reserved transparent index
            indices = bytearray(indexed.tobytes())
            visible = [i for i in range(255) if palette[i * 4 + 3] > 0]
            replacements = {}
            for i, pixel in enumerate(pixels):
                if pixel[3] == 0:
                    indices[i] = 255
                elif palette[indices[i] * 4 + 3] == 0:
                    # Octree may merge tiny-alpha edges into alpha=0. Keep the
                    # original occupied mask by choosing a nonzero-alpha color.
                    if pixel not in replacements:
                        replacements[pixel] = min(visible, key=lambda j: sum(
                            (palette[j * 4 + k] - pixel[k]) ** 2 for k in range(4)))
                    indices[i] = replacements[pixel]
            indexed.frombytes(bytes(indices))
            indexed.putpalette(palette, rawmode="RGBA")
            rgba = indexed.convert("RGBA")
            # LVGL lv_color32_t on ESP32 is byte ordered blue, green, red, alpha.
            bgra = bytes(v for i in range(0, 1024, 4)
                         for v in (palette[i + 2], palette[i + 1], palette[i], palette[i + 3]))
            blob = bgra + indexed.tobytes()
            assert len(blob) == FRAME_BYTES
            # Transparent canvas and opaque interior remain transparent/opaque.
            for before, after in zip(cell.getchannel("A").get_flattened_data(), rgba.getchannel("A").get_flattened_data()):
                assert (before == 0) == (after == 0)
            index = len(chunks)
            chunks.append(blob)
            frames.append(dict(index=index, state=name, row=row, column=col,
                               offset=index * FRAME_BYTES, bytes=FRAME_BYTES,
                               sha256=hashlib.sha256(blob).hexdigest()))
            previews.append(rgba)
    blob = b"".join(chunks)
    assert len(chunks) == 57 and len(blob) == 2334720
    header = '''// Generated by firmware/tools/avatar_convert.py; do not edit.
#pragma once
#include "lvgl.h"
#define AVATAR_FRAME_COUNT 57
#define AVATAR_FRAME_BYTES 40960
#define AVATAR_WIDTH 192
#define AVATAR_HEIGHT 208
typedef enum {
'''
    header += "".join("    AVATAR_" + name.upper().replace("-", "_") + ",\n" for name, _ in ROWS)
    header += '''    AVATAR_SEQUENCE_COUNT
} avatar_sequence_id_t;
typedef struct { uint8_t first, count; uint16_t frame_ms; } avatar_sequence_t;
extern const lv_image_dsc_t avatar_frames[AVATAR_FRAME_COUNT];
extern const avatar_sequence_t avatar_sequences[AVATAR_SEQUENCE_COUNT];
'''
    c = '''// Generated by firmware/tools/avatar_convert.py; do not edit.
#include "avatar_frames.h"
extern const uint8_t avatar_blob[] asm("_binary_avatar_frames_bin_start");
const lv_image_dsc_t avatar_frames[AVATAR_FRAME_COUNT] = {
'''
    for i in range(57):
        c += ('    {.header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_I8, '
              '.w = 192, .h = 208, .stride = 192}, '
              f'.data_size = AVATAR_FRAME_BYTES, .data = avatar_blob + {i * FRAME_BYTES}' + '},\n')
    c += '};\nconst avatar_sequence_t avatar_sequences[AVATAR_SEQUENCE_COUNT] = {\n'
    first = 0
    for name, count in ROWS:
        c += f'    {{{first}, {count}, {140 if name == "waving" else 150}}}, // {name}\n'
        first += count
    c += '};\n'
    manifest = dict(format="LVGL9 I8, 256 BGRA palette entries then 192x208 indices",
                    source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                    pillow=Image.__version__, bytes=len(blob), frames=frames,
                    sha256=hashlib.sha256(blob).hexdigest())
    return {"avatar_frames.bin": blob, "avatar_frames.h": header.encode(),
            "avatar_frames.c": c.encode(),
            "avatar_manifest.json": (json.dumps(manifest, indent=2) + "\n").encode()}, previews


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="regenerate in memory and verify committed bytes")
    parser.add_argument("--preview", type=Path, help="optional contact sheet PNG output")
    args = parser.parse_args()
    outputs, previews = convert()
    for name, data in outputs.items():
        path = ASSETS / name
        if args.check:
            assert path.read_bytes() == data, f"out of date: {path}"
        else:
            path.write_bytes(data)
    if args.preview:
        canvas = Image.new("RGBA", (8 * W, 9 * H), "#101923")
        i = 0
        for row, (_, count) in enumerate(ROWS):
            for col in range(count):
                canvas.alpha_composite(previews[i], (col * W, row * H))
                i += 1
        canvas.convert("RGB").save(args.preview)
    print("Verified" if args.check else "Generated", "57 frames; 2,334,720 bytes (2.2265625 MiB)")


if __name__ == "__main__":
    main()
